package searchsim.cfg;
/////////////////////////////////////////////////////////////////////////////////////////////////////////////
import java.util.Set;
import java.util.HashSet;
import ast.Declaration;
/////////////////////////////////////////////////////////////////////////////////////////////////////////////
public class CFGSkipNode extends CFGBasicBlockNode {

  public CFGSkipNode() {
    super();
  }
/////////////////////////////////////////////////////////////////////////////////////////////////////////////
  @Override
  public Set<Declaration> getReadSet() {
    // SkipNode has no reads
    return new HashSet<>();
  }

  @Override
  public Set<Declaration> getWriteSet() {
    // SkipNode has no writes
    return new HashSet<>();
  }
/////////////////////////////////////////////////////////////////////////////////////////////////////////////
  public String toString() {
    return this.cfg.name+" : "+ "Skip Node";
  }
  
}
